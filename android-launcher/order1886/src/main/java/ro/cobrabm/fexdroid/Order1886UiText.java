  static String translate(Context ctx,String text){
    if(text==null)return "";
    SharedPreferences prefs=ctx.getSharedPreferences("order1886",Context.MODE_PRIVATE);
    String setting=prefs.getString("appLanguage","auto");
    boolean pt="pt".equals(setting)||("auto".equals(setting)&&"pt".equals(Locale.getDefault().getLanguage()));
    if(pt)return text;
    for(Map.Entry<String,String> part:EN.entrySet())text=text.replace(part.getKey(),part.getValue());
    return text;
  }
